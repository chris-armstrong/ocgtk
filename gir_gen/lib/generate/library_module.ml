open StdLabels
open Types

(* The main library's module is generated by dune (a written one breaks odoc's
   links to layer 2 parents), so the generator only adds modules to it:
   [Raw] re-exports the raw library and [Enums] the enums library.

   [Raw] cannot be a single alias, which only dune's main module could hold.
   One alias per layer 1 module keeps odoc linking [Raw.Point.t] to the raw
   library's page. Members of a cycle have their own shim module in the raw
   library, so they need no cluster in the path. *)

let generated_header = "(* GENERATED CODE - DO NOT EDIT *)\n\n"

let raw_module_aliases ~ctx ~entity_names ~core_modules =
  let raw_module = Module_paths.raw_module ctx.namespace.namespace_name in
  let alias m = (m, raw_module ^ "." ^ m) in
  (List.map ~f:Utils.module_name_of_class entity_names
  |> List.sort ~cmp:String.compare)
  @ core_modules
  |> List.map ~f:alias

let generate_raw_module ~ctx ~entity_names ~core_modules =
  let buf = Buffer.create 4096 in
  Buffer.add_string buf generated_header;
  Gen_buffer.bprintf buf
    "(** Layer 1: externals and the abstract [t] for each %s type. *)\n\n"
    ctx.namespace.namespace_name;
  raw_module_aliases ~ctx ~entity_names ~core_modules
  |> List.iter ~f:(fun (alias, path) ->
      Gen_buffer.bprintf buf "module %s = %s\n" alias path);
  Buffer.contents buf

let generate_enums_module ~namespace =
  Fmt.str "%s(** %s enumerations and bitfields. *)\n\ninclude %s\n"
    generated_header namespace
    (Module_paths.enums_module namespace)

(* The main module is dune's, so it carries no docs and its page shows each
   module as a bare [sig ... end]. The package's hand-written [index.mld]
   links this page instead, which lists the modules by kind. *)

let modules_page_name = "modules"

let generate_modules_page ~namespace ~entities =
  let main_module = Module_paths.main_module namespace in
  let classes, interfaces, records =
    List.fold_left entities ~init:([], [], [])
      ~f:(fun (classes, interfaces, records) (e : entity) ->
        let m = Utils.module_name_of_class e.name in
        match e.kind with
        | Class _ -> (m :: classes, interfaces, records)
        | Interface _ -> (classes, m :: interfaces, records)
        | Record _ -> (classes, interfaces, m :: records))
  in
  let kinds =
    List.filter
      ~f:(fun (_, _, names) -> not (List.is_empty names))
      [
        ("Classes", "class", classes);
        ("Interfaces", "interface", interfaces);
        ("Records", "record", records);
      ]
  in
  let section (heading, _, names) =
    Fmt.str "{1 %s}\n\n{!modules:\n%s}\n" heading
      (String.concat ~sep:""
         (List.map (List.sort ~cmp:String.compare names) ~f:(fun m ->
              Fmt.str "  %s.%s\n" main_module m)))
  in
  (* "a", "a and b", "a, b and c" *)
  let listing words =
    match List.rev words with
    | [] -> ""
    | [ w ] -> w
    | last :: rest -> String.concat ~sep:", " (List.rev rest) ^ " and " ^ last
  in
  Fmt.str
    "{0 %s %s}\n\n\
     {!%s} has one module for each %s %s. The externals they are built on are \
     in {!%s.Raw}.\n\n\
     %s"
    namespace
    (listing
       (List.map kinds ~f:(fun (heading, _, _) ->
            String.lowercase_ascii heading)))
    main_module namespace
    (listing (List.map kinds ~f:(fun (_, singular, _) -> singular)))
    main_module
    (String.concat ~sep:"\n" (List.map ~f:section kinds))
